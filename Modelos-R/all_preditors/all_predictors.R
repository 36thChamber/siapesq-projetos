# Crie o nome do arquivo com a data atual
data_atual <- format(Sys.Date(), "%d%m%y")

# Mugil liza
setwd("/workspace/map-api/mugil_liza")
modeloUbrasiliensis <- read.sdm("/workspace/map-api/mugil_liza/mugil_liza_rf.sdm")
setwd("/workspace/map-api")
nc_files <- list.files(path="/workspace/map-api/variables_CHL", pattern = "*nc$", full.names = TRUE)
r <- lapply(nc_files, raster)
ref_raster <- r[[1]]
r_resampled <- lapply(r, function(x) resample(x, ref_raster, method = "bilinear"))
bio_presente_cop <- stack(r_resampled)
names(bio_presente_cop) <- c("depth", "CHL","so","thetao")
predictTeste3 = predict(modeloUbrasiliensis, bio_presente_cop, meant= T, na.rm= T)
writeRaster(predictTeste3, filename = "/workspace/map-api/dashboard/mugil_liza.tif", format = "GTiff", overwrite = TRUE, datatype = "FLT4S")
print("foi liza")

